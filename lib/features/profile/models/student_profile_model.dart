class StudentProfileModel {
  final String name;
  final String usn;
  final String department;
  final String year;
  final String busNumber;
  final String route;
  final String profilePhoto;

  const StudentProfileModel({
    required this.name,
    required this.usn,
    required this.department,
    required this.year,
    required this.busNumber,
    required this.route,
    required this.profilePhoto,
  });
}